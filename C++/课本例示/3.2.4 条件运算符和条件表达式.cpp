// 文件：3.2.4 条件运算符和条件表达式.cpp
// 整体总结：演示条件运算符“? :”的用法。
// 从键盘读取一个字符，如果它是小写字母 a 到 z，就转换成对应的大写字母；
// 否则保持原字符不变，然后输出结果。
#include <stdio.h>  // 引入标准输入输出库，使用 puts、getchar、putchar
#include "string.h" // 引入字符串相关头文件（本例实际未用到其中的函数）
void main()         // 程序主函数，原代码使用旧式 void main
{
    char c;                                           // 定义字符型变量 c，用来保存读取到的字符
    puts("please input one char:");                   // 输出提示信息并自动换行
    c = getchar();                                    // 从标准输入读取一个字符，存入 c
    c = (c <= 'z' && c >= 'a' ? (c + 'A' - 'a') : c); // 条件表达式：若 c 是小写字母，则 c + 'A' - 'a' 转成大写；否则保持 c 不变，最后赋回 c
    putchar(c);                                       // 输出转换后的字符
    putchar('\n');                                    // 输出一个换行符
}