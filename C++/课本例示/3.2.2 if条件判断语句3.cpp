// 文件：3.2.2 if条件判断语句3.cpp
// 整体总结：演示 if 条件不成立时的执行情况。
// 先把 a 赋给 x，如果 a > b 成立才把 b 赋给 x；否则 x 保持为 a。
#include <stdio.h> // 引入标准输入输出库，使用 printf
void main()        // 程序主函数，原代码使用旧式 void main
{
    int a = 10, b = 20, x; // 定义 a、b、x，并初始化 a 为 10，b 为 20
    x = a;                 // 先把 a 的值 10 赋给 x
    if (a > b)             // 判断 a > b，即 10 > 20，不成立
        x = b;             // 条件成立时才会执行；本例条件不成立，所以本行不执行
    printf("%d\n", x);     // 输出 x 的值，预期输出 10
}