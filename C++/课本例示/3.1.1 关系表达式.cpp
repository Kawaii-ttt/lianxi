// 文件：3.1.1 关系表达式.cpp
// 整体总结：演示赋值表达式“=”和关系表达式“==”的区别：
// z1 = (x = y) 先把 y 赋给 x，再把赋值结果赋给 z1；
// z2 = (x == y) 判断 x 和 y 是否相等，把比较结果赋给 z2。
#include <stdio.h> // 引入标准输入输出库，使用 printf
void main()        // 程序主函数，原代码使用旧式 void main
{
    int x, y, z1, z2;          // 定义整型变量 x、y、z1、z2
    x = 2;                     // 给 x 赋值为 2
    y = 2;                     // 给 y 赋值为 2
    z1 = (x = y);              // 先执行赋值 x = y，x 变为 2，整个括号表达式的值也是 2，再赋给 z1
    z2 = (x == y);             // 判断 x 是否等于 y，相等结果为 1，不相等为 0，此处结果为 1，赋给 z2
    printf("%d,%d\n", z1, z2); // 按整数输出 z1 和 z2，预期输出：2,1
}