// 文件：3.1.1 关系表达式2.cpp
// 整体总结：演示关系运算符、逻辑真假值、运算符优先级和左结合性。
// 关系表达式成立结果为 1，不成立结果为 0；多个关系运算符连续使用时要注意结合方向。
#include <stdio.h> // 引入标准输入输出库，使用 printf
void main()        // 程序主函数，原代码使用旧式 void main
{
    int x, y, z, i, j;               // 定义整型变量 x、y、z、i、j
    x = 4, y = 3, z = 2;             // 逗号表达式依次执行：x 赋 4，y 赋 3，z 赋 2
    i = y > z;                       // 判断 y > z，即 3 > 2 成立，i 得到 1
    j = x > y > z;                   // 关系运算符左结合：先算 x > y 得 1，再算 1 > z 即 1 > 2，结果为 0，j 得到 0
    printf("%2d,%2d,", i, j);        // 以宽度 2 输出 i 和 j，预期先输出： 1, 0,
    printf("%2d,", z > y == 3);      // 先算 z > y 得 0，再算 0 == 3 得 0，输出 0
    printf("%2d,", y + z < x);       // 先算 y + z 得 5，再算 5 < x 即 5 < 4 不成立，输出 0
    printf("%2d\n", y + 2 >= z + 1); // 先算 y + 2 得 5，z + 1 得 3，5 >= 3 成立，输出 1
}