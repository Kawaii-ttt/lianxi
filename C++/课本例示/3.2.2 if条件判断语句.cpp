// 文件：3.2.2 if条件判断语句.cpp
// 整体总结：输入一个整数 x，如果 x 小于 0，就把它变成相反数，
// 从而输出该整数的绝对值。
#include <stdio.h> // 引入标准输入输出库，使用 scanf 和 printf
void main()        // 程序主函数，原代码使用旧式 void main
{
    int x;                 // 定义整型变量 x
    scanf("%d", &x);       // 从键盘读取一个整数并存入 x
    if (x < 0)             // 判断 x 是否小于 0
        x = -x;            // 如果 x 小于 0，就把 x 取相反数，使其变为正数
    printf("|x|=%d\n", x); // 输出绝对值结果，格式为 |x|=数值
}